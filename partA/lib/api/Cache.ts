/**
 * Кэш сангийн ерөнхий интерфейс.
 * 
 * LRU, LFU, TTL гэх мэт бүх төрлийн кэшүүд үүнийг хэрэгжүүлнэ.
 * Программд кэш ашиглахдаа зөвхөн энэ интерфейсээр харьцах ёстой.
 * Ингэснээр цаана нь ямар алгоритм ажиллаж байгаагаас үл хамааран 
 * кодын бусад хэсэг тогтвортой үлдэнэ.
 */
export interface Cache<V> {
  /**
   * Ключээр хайж утгыг авна. 
   * Байхгүй бол null буцаана.
   */
  get(key: string): V | null;

  /**
   * Өгөгдлийг кэшэд хадгалах эсвэл шинэчлэх.
   * Кэш дүүрсэн үед тухайн алгоритмын (LRU/LFU/TTL) дагуу 
   * зай гаргахын тулд зарим өгөгдлийг устгадаг.
   */
  set(key: string, value: V): void;

  /** Кэшэд тухайн ключ байгаа эсэхийг шалгах */
  has(key: string): boolean;

  /** Тухайн нэг ключийг кэшээс гаргах */
  delete(key: string): boolean;

  /** Кэшийг бүрэн хоослох */
  clear(): void;

  /** Одоо кэшэд хэдэн элемент байгааг харуулна */
  size(): number;
}